"""The contract pages: one Markdown page per group of contracts (a host's pack, a domain) with a section per contract, and an index of
every contract. The sections' body (fields, nested records, links, validation, notes, points to review) is the product's; what a host
says around it (its header, a group's introduction, the rows of a contract's summary table, the index's columns) comes from its
``PageProfile``, a subclass that overrides the methods below. The core profile writes plain pages from the core keys alone."""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class Entry:
    """One table kind of a group: its name (a host's command, else the kind), kind, group, contract file and contract (None: none yet)."""
    name: str
    kind: str
    group: str
    file: Path | None
    contract: dict | None


def cell(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ").strip()


def table(head: list, rows: list) -> list[str]:
    """A Markdown table and the blank line after it."""
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows] + [""]


def v(x) -> str:
    """A value in a table cell: a list as code spans, nothing as a dash."""
    if isinstance(x, list):
        return ", ".join(f"`{i}`" for i in x) if x else "—"
    if x in (None, ""):
        return "—"
    return str(x)


def slug(text: str) -> str:
    """GitHub's anchor of a heading's text (lower case, punctuation dropped, spaces to hyphens)."""
    return re.sub(r"[^\w\- ]", "", text.lower()).replace(" ", "-")


class PageProfile:
    """What a host writes around the product's sections. Override any method; the defaults use the core keys only."""

    generator = "drishti_lake.contracts pages"

    def header(self) -> list[str]:
        """The lines every page starts with."""
        return [f"<!-- Generated by {self.generator}. Edit the contracts, not this file. -->", ""]

    def title(self, c: dict) -> str:
        """A contract's heading text (its anchor is ``slug`` of it)."""
        return f"{c['title']} ({c['kind']})"

    def heading(self, c: dict) -> str:
        return f"## {c['title']} (`{c['kind']}`)"

    def anchor(self, c: dict) -> str:
        return slug(self.title(c))

    def status(self, c: dict) -> str:
        if c.get("status") == "planned":
            return "planned: no data yet"
        return f"retiring in {c['retiring-in']}" if c.get("status") == "retiring" else "active"

    def rows(self, c: dict, f: Path | None, group: str) -> list[list]:
        """The contract's summary table (two columns: what, value)."""
        return [["Contract", f"{f.name if f else c['kind']} · version {c['version']}"],
                ["Status", self.status(c) + (f", replaced by {c['replaced-by']}" if c.get("replaced-by") else "")],
                ["Source", c["source"]], ["Grain", c["grain"]], ["Key", v(c.get("key"))], ["Id pattern", v(c.get("id-pattern"))],
                ["Dated by", f"`{c['dated-by']}`"], ["Cadence", f"{c['cadence']['frequency']} (due: {c['cadence']['due']})"]]

    def group_page(self, group: str) -> str:
        """The file name of a group's page."""
        return f"{group}.md"

    def group_intro(self, group: str) -> list[str]:
        return [f"# Data contracts of {group}", ""]

    def summary(self, entries: list[Entry]) -> list[str]:
        """A group page's table of its contracts, before the sections."""
        return table(["Kind", "Status", "Fields", "To review"], [[
            f"[`{e.kind}`](#{self.anchor(e.contract)})", self.status(e.contract), str(len(e.contract.get("fields") or [])),
            str(len(e.contract.get("review") or []))] for e in entries if e.contract])

    def planned_intro(self) -> list[str]:
        return ["## Planned", "", "Contracts of kinds designed before their data exists (`status: planned`).", ""]

    def planned_summary(self, plans: list[Entry]) -> list[str]:
        return self.summary(plans)

    def index_intro(self, entries: list[Entry], plans: list[Entry]) -> list[str]:
        return ["# Data contracts", "", f"{sum(1 for e in entries if e.contract)} contracts.", ""]

    def index_table(self, entries: list[Entry], plans: list[Entry]) -> list[str]:
        rows = [[f"`{e.kind}`", e.group, "—", "no contract"] if not e.contract else
                [f"`{e.kind}`", f"[{e.group}]({self.group_page(e.group)}#{self.anchor(e.contract)})", self.status(e.contract),
                 str(len(e.contract.get("review") or []))] for e in entries + plans]
        return table(["Kind", "Group", "Status", "To review"], rows)


def section(p: PageProfile, c: dict, f: Path | None, group: str) -> list[str]:
    """One contract's section: heading, description, summary table, fields, nested records, links, validation, notes, points to review."""
    out = [p.heading(c), "", c.get("description", ""), ""]
    out += table(["", ""], p.rows(c, f, group))

    def ftable(fs: list[dict]) -> list[str]:
        return table(["Field", "Type", "Presence", "Unit", "Description", "Example or values", "Link"], [[
            f"`{x['name']}`", x["type"], x["presence"] + (f" (retiring in {x['retiring-in']})" if x.get("retiring-in") else ""), x.get("unit", ""),
            (x.get("description") or "—") + (f" *{x['note']}*" if x.get("note") else ""),
            (", ".join(f"`{e}`" for e in x["enum"]) if x.get("enum") else (f"`{x['example']}`" if x.get("example") not in (None, "") else ""))
            + (f" (pattern `{x['pattern']}`)" if x.get("pattern") else ""),
            f"`{x['link']}`" if x.get("link") else ""] for x in fs])

    out += ["**Fields**", ""] + ftable(c.get("fields") or [])
    for path, fs in (c.get("nested") or {}).items():
        out += [f"**Nested `{path}`**", ""] + ftable(fs)
    if c.get("links"):
        out += ["**Links:** " + ", ".join(f"`{x['field']}` → `{x['kind']}`" for x in c["links"]) + ".", ""]
    if c.get("validation"):
        out += ["**Validation**", ""]
        for r in c["validation"]:
            extra = {k: val for k, val in r.items() if k != "rule"}
            out.append(f"- {r['rule']}: " + "; ".join(f"{k} {v(val) if isinstance(val, list) else val}" for k, val in extra.items()))
        out.append("")
    if c.get("notes"):
        out += ["**Notes**", ""] + [f"- {n}" for n in c["notes"]] + [""]
    if c.get("review"):
        out += [f"**To review ({len(c['review'])})**", ""] + [f"- {n}" for n in c["review"]] + [""]
    return out


def render_group(p: PageProfile, group: str, entries: list[Entry], plans: list[Entry] = ()) -> str:
    """A group's page: the profile's header and introduction, the summary, a section per contract, then its planned contracts."""
    out = p.header() + p.group_intro(group) + p.summary(entries)
    for e in entries:
        if e.contract:
            out += section(p, e.contract, e.file, group)
    if plans:
        out += p.planned_intro() + p.planned_summary(list(plans))
        for e in plans:
            out += section(p, e.contract, e.file, group)
    return "\n".join(out).rstrip() + "\n"


def render_index(p: PageProfile, entries: list[Entry], plans: list[Entry] = ()) -> str:
    out = p.header() + p.index_intro(entries, list(plans)) + p.index_table(entries, list(plans))
    return "\n".join(out).rstrip() + "\n"


def render(p: PageProfile, entries: list[Entry], plans: list[Entry] = (), index: str = "README.md") -> dict[str, str]:
    """Every page by file name: a page per group (in name order, a group's planned contracts after its others) and the index."""
    out = {}
    for group in sorted({e.group for e in entries} | {e.group for e in plans}):
        out[p.group_page(group)] = render_group(p, group, [e for e in entries if e.group == group], [e for e in plans if e.group == group])
    out[index] = render_index(p, entries, plans)
    return out


def write(pages: dict[str, str], folder: Path, check: bool = False) -> tuple[list[str], list[str]]:
    """Writes the pages into ``folder`` (only those that changed) and removes the folder's other ``*.md`` files; with ``check``, writes
    nothing. Returns (stale or written, removed or to remove) by file name."""
    folder = Path(folder)
    stale = [n for n, text in pages.items() if not (folder / n).is_file() or (folder / n).read_text(encoding="utf-8") != text]
    extra = sorted(f.name for f in folder.glob("*.md") if f.name not in pages) if folder.is_dir() else []
    if not check:
        folder.mkdir(parents=True, exist_ok=True)
        for n in stale:
            (folder / n).write_text(pages[n], encoding="utf-8")
        for n in extra:
            (folder / n).unlink()
    return stale, extra
