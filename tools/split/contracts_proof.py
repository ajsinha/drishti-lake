"""The proof of step L11 (design section 7): every data contract of the host's checkout (read only, at the freeze commit) reads through
drishti_lake.contracts to what it holds, is valid against the core schema with the host's profile (and that schema is the host's own),
every record of its samples gets the same answer from the Java and the Python checker is left to the kit; and its generated pages
(docs/contracts/packs/*.md) are byte-identical when written by drishti_lake.contracts.pages with the host's PageProfile below. The
profile is the rehearsal of the host's adapter (G4): the host's words, its keys, its pack folders; the product holds none of them.

    python3 tools/split/contracts_proof.py /path/to/drishti-checkout

Exit 0 when every contract reads and validates identically and every page is byte-identical. Writes nothing."""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python"))
from drishti_lake import contracts as K  # noqa: E402
from drishti_lake.contracts import pages as P  # noqa: E402

# the host's own keys (its contract profile): what its schema adds to the core's
HOST_PROFILE = K.Profile(
    title="Drishti data contract of one command (mnemonic) kind",
    required=("mnemonic", "pack", "class", "binding-hint"),
    properties={
        "mnemonic": {"type": "string", "pattern": "^[A-Z][A-Z0-9]*$"},
        "pack": {"type": "string", "pattern": "^[a-z][a-z0-9-]*$"},
        "class": {"enum": ["fundamental", "input", "drishti-owned", "computed"]},
        "replaced-by": {"type": "string", "pattern": "^docs/contracts/[A-Z_]+\\.md$"},
        "list": {
            "description": "How the kind may be listed: requires names the fields one of which must narrow a list (a vector-heavy input is never listed whole).",
            "type": "object", "additionalProperties": False, "required": ["requires"],
            "properties": {"requires": {"type": "array", "minItems": 1, "items": {"type": "string", "pattern": "^[A-Z][A-Z0-9_.]*$"}},
                           "why": {"type": "string"}}},
        "binding-hint": {
            "description": "What a site usually binds (docs/architecture/KERNEL_AND_MODULES.md section 5.2): never a connector, a plugin or a location.",
            "type": "object", "additionalProperties": False,
            "properties": {
                "lake-table": {"type": "string", "pattern": "^[a-z0-9_-]+\\.[a-z0-9_.-]+$"},
                "partition": {"type": "array", "items": {"type": "string"}},
                "live": {"enum": ["optional", "required", "none"]},
                "computed": {"type": "boolean"},
                "columns": {"type": "array", "items": {"type": "string"}},
                "vectors": {"type": "array", "items": {"type": "string"}},
                "test-data": {"type": "array", "items": {"type": "string"}}}}})


class HostPages(P.PageProfile):
    """The host's words around the product's sections (its tools/contracts.py at the freeze, rendering half)."""
    generator = "tools/contracts.py docs (drishti.py contract docs)"

    def __init__(self, checkout: Path, packs: dict[str, Path]):
        self.root, self.packs = checkout, packs
        lines = (checkout / "docs" / "guides" / "RACHANA_REFERENCE.md").read_text(encoding="utf-8").splitlines()
        self.licence = "\n".join(lines[:lines.index("-->") + 1])
        self.testdata = yaml.safe_load((checkout / "data" / "testdata" / "testdata.yaml").read_text(encoding="utf-8")) or {}

    def header(self):
        return [self.licence, f"<!-- Generated by {self.generator} from config/packs/*/contracts/*.contract.yaml. Edit the contracts, not this file. -->", ""]

    def title(self, c):
        return f"{c['mnemonic']}: {c['title']} ({c['kind']})"

    def heading(self, c):
        return f"## {c['mnemonic']}: {c['title']} (`{c['kind']}`)"

    def planned_demo(self, c):
        if c.get("status") != "planned" or c.get("class") not in ("input", "fundamental"):
            return []
        return sorted((self.root / "data" / "testdata" / c["pack"] / c["kind"]).glob("*.jsonl.gz"))

    def status(self, c):
        if c.get("status") == "planned":
            return "planned: no command yet; demo data generated, not loaded" if self.planned_demo(c) else "planned: no command or data yet"
        return f"retiring in {c['retiring-in']}" if c.get("status") == "retiring" else "active"

    def sample_pages(self, c):
        sets = [d for d in self.testdata.get("datasets") or [] if d.get("pack") == c["pack"] and d.get("kind") == c["kind"] and not d.get("native")]
        folders = [d["folder"] for d in sets if d.get("folder")]
        if folders:
            return folders
        if self.planned_demo(c):
            return [f"{c['pack']}/{c['kind']}"]
        samples = self.packs[c["pack"]] / "samples"
        if c.get("class") in ("input", "fundamental") and (any(samples.glob(f"{c['kind']}.jsonl")) or any(samples.glob(f"{c['kind']}.part-*.jsonl"))):
            return [f"{c['pack']}/{c['kind']}"]
        return []

    def where(self, group):
        return self.packs[group].resolve().relative_to(self.root.resolve()).as_posix()

    def rows(self, c, f, group):
        st = c.get("binding-hint") or {}
        where = ("computed by Drishti, never bound" if st.get("computed")
                 else (f"lake table `{st['lake-table']}`" if st.get("lake-table") else "any source the site binds"))
        rows = [["Contract", f"[{f.name}](../../../{self.where(group)}/contracts/{f.name}) · version {c['version']}"],
                ["Class", c["class"]], ["Status", self.status(c) + (f", replaced by {c['replaced-by']}" if c.get("replaced-by") else "")],
                ["Source", c["source"]], ["Grain", c["grain"]], ["Key", P.v(c.get("key"))], ["Id pattern", P.v(c.get("id-pattern"))],
                ["Dated by", f"`{c['dated-by']}`"], ["Cadence", f"{c['cadence']['frequency']} (due: {c['cadence']['due']})"],
                ["Binding hint", where + "; the site binds it (`config/bindings.yaml`, Admin → Data bindings)"]]
        for k, label in (("columns", "Columns"), ("vectors", "Vectors"), ("partition", "Partitioned by")):
            if st.get(k):
                rows.append([label, P.v(st[k])])
        if st.get("test-data"):
            rows.append(["Test data", ", ".join(st["test-data"])])
        worked = self.sample_pages(c)
        if worked:
            rows.append(["Worked example", " · ".join(f"[{n}](../samples/{n.split('/', 1)[0]}.md#{n.split('/', 1)[1]})" for n in worked)
                         + " (a real record, every field explained, for the production query; tools/testdata/sample_docs.py)"])
        return rows

    def group_intro(self, pack):
        where = self.where(pack)
        return [f"# Data contracts of the {pack} pack", "",
                f"One section per command of the pack: the shape of its data, how it is stored and checked, and what a person still "
                f"has to confirm. The rules every contract shares are in [the contracts README](../README.md); the index of every "
                f"command is [packs/README.md](README.md). The pack's guide, "
                f"[{where}/guides/{pack}.md](../../../{where}/guides/{pack}.md), links each kind here and to "
                f"its example (tools/packgen/common/guide_data.py) next to how to use the pack and where each kind's data comes "
                f"from (*Data retrieval*).", ""]

    def summary(self, entries):
        return P.table(["Command", "Kind", "Class", "Status", "Fields", "To review"], [[
            f"[{c['mnemonic']}](#{self.anchor(c)})", f"`{c['kind']}`", c["class"], self.status(c), str(len(c.get('fields') or [])),
            str(len(c.get('review') or []))] for c in (e.contract for e in entries) if c])

    def planned_intro(self):
        return ["## Planned inputs", "",
                "Contracts of inputs designed before their data exists (`status: planned`): no command and no engine reads them yet, "
                "and `lake demo` loads none (a few have demo data from a generator, for their sample page). Each is the shape a bank delivers once the feature that reads it is built; until then a person may still "
                "change it.", ""]

    def planned_summary(self, plans):
        return P.table(["Proposed command", "Kind", "Class", "Status", "Fields", "To review"], [[
            f"[{c['mnemonic']}](#{self.anchor(c)})", f"`{c['kind']}`", c["class"], self.status(c), str(len(c.get('fields') or [])),
            str(len(c.get('review') or []))] for c in (e.contract for e in plans)])

    def index_intro(self, entries, plans):
        total = sum(len(e.contract.get("review") or []) for e in entries if e.contract)
        return ["# Data contracts of every command", "",
                "Every command (mnemonic) of every pack has a data contract: a YAML file beside its pack "
                "(`modules/<module>/packs/<pack>/contracts/<kind>.contract.yaml`, checked against `tools/contracts.schema.json`) and a section of "
                "its pack's page here. The shared rules are in [the contracts README](../README.md); the computed measures that replace "
                "the retiring kinds have their own contracts there.", "",
                f"{sum(1 for e in entries if e.contract)} contracts, {total} points still to review. Check them with "
                "`drishti.py contract check`; draft a new one with `drishti.py contract bootstrap KIND --write`.", ""]

    def index_table(self, entries, plans):
        rows = []
        for e in entries:
            c = e.contract
            if not c:
                rows.append([f"`{e.name}`", f"`{e.kind}`", e.group, "—", "no contract", "", ""])
                continue
            rows.append([f"`{c['mnemonic']}`", f"`{c['kind']}`", f"[{c['pack']}]({c['pack']}.md#{self.anchor(c)})", c["class"], self.status(c),
                         c.get("replaced-by", "").replace("docs/contracts/", "") or "", str(len(c.get("review") or []))])
        for e in plans:
            c = e.contract
            rows.append([f"`{c['mnemonic']}` (proposed)", f"`{c['kind']}`", f"[{c['pack']}]({c['pack']}.md#{self.anchor(c)})", c["class"],
                         self.status(c), "", str(len(c.get("review") or []))])
        return P.table(["Command", "Kind", "Pack", "Class", "Status", "Replaced by", "To review"], rows)


def pack_dirs(checkout: Path) -> dict[str, Path]:
    """The host's packs (config/packs/<group>/<pack>, modules/<module>/packs/<pack>) by name, in name order."""
    found = [p.parent for p in sorted(checkout.glob("config/packs/*/*/pack.yaml")) + sorted(checkout.glob("modules/*/packs/*/pack.yaml"))]
    return dict(sorted((d.name, d) for d in found))


def entries(checkout: Path, packs: dict[str, Path]) -> tuple[list, list]:
    """(one entry per command of every pack in pack then manifest order, the planned contracts)."""
    out, known = [], set()
    for name, d in packs.items():
        m = yaml.safe_load((d / "pack.yaml").read_text(encoding="utf-8")) or {}
        for code, spec in (m.get("mnemonics") or {}).items():
            if isinstance(spec, dict) and spec.get("kind"):
                f = d / "contracts" / f"{spec['kind']}.contract.yaml"
                known.add(f.resolve())
                out.append(P.Entry(code, spec["kind"], name, f, K.load(f) if f.is_file() else None))
    plans = []
    for d in packs.values():
        for f in sorted(d.glob("contracts/*.contract.yaml")):
            if f.resolve() not in known:
                c = K.load(f)
                if c.get("status") == "planned":
                    plans.append(P.Entry(c.get("mnemonic"), c["kind"], c.get("pack"), f, c))
    return out, plans


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        sys.exit(__doc__)
    checkout = Path(argv[0]).resolve()
    bad = 0
    host_schema = json.loads((checkout / "tools" / "contracts.schema.json").read_text(encoding="utf-8"))
    mine = HOST_PROFILE.schema()
    for k in ("type", "additionalProperties", "properties", "allOf", "$defs"):
        if mine.get(k) != host_schema.get(k):
            print(f"schema: {k} differs from the host's")
            bad += 1
    if sorted(mine["required"]) != sorted(host_schema["required"]):
        print("schema: required differs from the host's")
        bad += 1
    files = sorted(checkout.glob("config/packs/*/*/contracts/*.contract.yaml")) + sorted(checkout.glob("modules/*/packs/*/contracts/*.contract.yaml"))
    for f in files:
        doc = yaml.safe_load(f.read_text(encoding="utf-8"))
        c = K.Contract.read(f, HOST_PROFILE)
        if c.doc != doc or set(c.host) != {k for k in HOST_PROFILE.host_keys() if k in doc}:
            print(f"{f.relative_to(checkout)}: read differently")
            bad += 1
        for p in K.schema_problems(doc, HOST_PROFILE):
            print(f"{f.relative_to(checkout)}: {p}")
            bad += 1
    packs = pack_dirs(checkout)
    items, plans = entries(checkout, packs)
    pages = P.render(HostPages(checkout, packs), items, plans)
    folder = checkout / "docs" / "contracts" / "packs"
    stale, extra = P.write(pages, folder, check=True)
    for n in stale + extra:
        print(f"page {n}: not byte-identical to the host's")
        bad += 1
    print(f"{len(files)} contracts read and valid ({bad} problems); {len(pages)} pages, {len(pages) - len(stale)} byte-identical, {len(extra)} extra")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
